// ─────────────────────────────────────────────────────────────────
// Helper: Ambil hadis Muslim berdasarkan ID
// ─────────────────────────────────────────────────────────────────
export function getMuslimHadithById(id) {
  return HADITH_MUSLIM.find(h => h.id === id) || null;
}

// ─────────────────────────────────────────────────────────────────
// Helper: Ambil semua hadis Muslim berdasarkan tema
// ─────────────────────────────────────────────────────────────────
export function getMuslimHadithsByTheme(themeKey) {
  const ids = HADITH_MUSLIM_THEMES[themeKey] || [];
  return ids.map(id => getMuslimHadithById(id)).filter(Boolean);
}
