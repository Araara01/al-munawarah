// ─────────────────────────────────────────────────────────────────
export function getHadithById(id) {
  return HADITH_BUKHARI.find(h => h.id === id) || null;
}

// ─────────────────────────────────────────────────────────────────
// Helper: Ambil semua hadis berdasarkan tema
// ─────────────────────────────────────────────────────────────────
export function getHadithsByTheme(themeKey) {
  const ids = HADITH_THEMES[themeKey] || [];
  return ids.map(id => getHadithById(id)).filter(Boolean);
}
